#!/usr/bin/env node
/*
 * Generates web/shared/config.js from environment variables.
 *
 * The repository only ever contains EMPTY values. The real values live in
 * GitHub "Actions secrets" (for the APK builds) and in Cloudflare Pages
 * "Environment variables" (for the website), and are injected here at build time.
 *
 * Usage:  GAS_URL=... GOOGLE_API_KEY=... node scripts/make-config.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const env = (name, fallback = '') => (process.env[name] || fallback).trim();

const config = {
  BRAND_AR: 'مركز دُر الرازي الطبي',
  BRAND_EN: 'Dur Al-Razi Medical Center',

  // Secrets / private values (empty in the repository)
  GAS_URL: env('GAS_URL'),
  GOOGLE_CLIENT_ID: env('GOOGLE_WEB_CLIENT_ID'),
  DRIVE_API_KEY: env('GOOGLE_API_KEY'),
  DROPBOX_APP_KEY: env('DROPBOX_APP_KEY'),
  ONEDRIVE_CLIENT_ID: env('ONEDRIVE_CLIENT_ID'),

  // Public values
  GITHUB_REPO: env('GITHUB_REPOSITORY', env('GITHUB_REPO')),
  RT_SERVER: env('RT_SERVER', 'https://ntfy.sh'),
  DEV_NAME: 'Hasn',
  DEV_SITE: 'https://hasn2mr.pages.dev',
  DRIVE_FOLDER_NAME: 'DurAlRazi Signage',

  // Playback defaults
  POLL_SEC: 60,
  IMAGE_SEC: 10,
  TEXT_SEC: 12,
  PAGE_SEC: 8,
};

const body = `/* Generated by scripts/make-config.mjs - do not edit, do not commit real values. */
window.DR = ${JSON.stringify(config, null, 2)};
`;

writeFileSync(join(root, 'web/shared/config.js'), body);

const missing = ['GAS_URL', 'DRIVE_API_KEY'].filter((key) => !config[key]);
if (missing.length) {
  console.warn(`WARN: empty config values: ${missing.join(', ')} (fine for local development only)`);
}
console.log('config.js written');
